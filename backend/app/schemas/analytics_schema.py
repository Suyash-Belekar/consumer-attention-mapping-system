class DashboardSummaryResponse(BaseModel):
    """Aggregated real-time metrics for executive store dashboard."""

    model_config = ConfigDict(
        from_attributes=True,
        frozen=True,
    )

    current_visitors: int = Field(
        ...,
        ge=0,
        description="Number of currently active visitors in the store.",
        examples=[12],
    )
    total_visitors: int = Field(
        ...,
        ge=0,
        description="Total distinct visitors recorded since the start of the timeframe.",
        examples=[145],
    )
    average_dwell_time: float = Field(
        ...,
        ge=0.0,
        description="Average dwell time across all store zones in seconds.",
        examples=[45.2],
    )
    top_product: Optional[str] = Field(
        default=None,
        description="Shelf or product zone name with the highest engagement score.",
        examples=["Beverage Aisle"],
    )
    peak_hour: Optional[str] = Field(
        default=None,
        description="Hour with peak visitor traffic (formatted string, e.g., '14:00').",
        examples=["14:00"],
    )


