class TrafficAnalyticsResponse(BaseModel):
    """Hourly traffic aggregated metric."""

    model_config = ConfigDict(
        from_attributes=True,
        frozen=True,
    )

    hour: str = Field(
        ...,
        description="Formatted hour timestamp (e.g., 'YYYY-MM-DD HH:00:00' or 'HH:00').",
        examples=["2026-07-29 14:00:00"],
    )
    visitors: int = Field(
        ...,
        ge=0,
        description="Count of distinct visitors observed during this hour.",
        examples=[28],
    )

    @field_validator("hour", mode="before")
    @classmethod
    def serialize_hour_field(cls, value: Union[str, datetime]) -> str:
        """Ensures datetime objects returned from database date_trunc are stringified safely."""
        if isinstance(value, datetime):
            return value.strftime("%Y-%m-%d %H:%00:%00")
        return str(value)


